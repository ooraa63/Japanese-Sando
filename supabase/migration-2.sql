-- 5. ATUR STOK GLOBAL
-- =============================================================================

create or replace function public.admin_set_stock(
  p_stock integer,
  p_note  text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old integer;
  v_new integer;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;
  if p_stock is null or p_stock < 0 then
    raise exception 'invalid_stock' using errcode = '22023';
  end if;

  select total_stock into v_old from public.store_settings where id = 1 for update;
  if not found then
    raise exception 'settings_missing' using errcode = '22023';
  end if;

  update public.store_settings set total_stock = p_stock where id = 1;
  v_new := p_stock;

  -- flavor_id NULL: log untuk stok gabungan seluruh toko.
  insert into public.stock_logs (flavor_id, delta, reason, note, actor_id)
  values (null, p_stock - v_old, 'global', coalesce(p_note, ''), auth.uid());

  return jsonb_build_object('total_stock', v_new, 'previous', v_old);
end;
$$;


