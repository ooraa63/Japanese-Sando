create or replace function public.admin_list_batches()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_open_id bigint;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  -- Pastikan ada batch terbuka SEBELUM membaca, supaya batch yang baru
  -- dibuat ikut terlihat di hasil.
  v_open_id := public.public_open_batch_id();

  return (
    select coalesce(jsonb_agg(
      jsonb_build_object(
        'id', b.id,
        'label', b.label,
        'note', b.note,
        'status', b.status,
        'created_at', b.created_at,
        'closed_at', b.closed_at,
        'order_count', (select count(*) from public.orders o where o.batch_id = b.id),
        'item_count', coalesce((select sum(o.item_count) from public.orders o where o.batch_id = b.id), 0),
        'revenue', coalesce((select sum(o.total_price) from public.orders o
                              where o.batch_id = b.id
                                and o.status in ('accepted','ready','delivered')), 0),
        'is_open', (b.id = v_open_id)
      ) order by b.created_at desc
    ), '[]'::jsonb)
    from public.batches b
  );
end;
$$;

create or replace function public.admin_close_batch(p_batch_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  update public.batches
  set status = 'closed', closed_at = now()
  where id = p_batch_id and status = 'open';

  if not found then
    raise exception 'batch_not_open' using errcode = '22023';
  end if;

  return jsonb_build_object('id', p_batch_id, 'status', 'closed');
end;
$$;

create or replace function public.admin_reopen_batch(p_batch_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  -- Tutup batch terbuka lain supaya hanya ada satu.
  update public.batches set status = 'closed', closed_at = coalesce(closed_at, now())
  where status = 'open' and id <> p_batch_id;

  update public.batches
  set status = 'open', closed_at = null
  where id = p_batch_id;

  if not found then
    raise exception 'batch_not_found' using errcode = 'P0002';
  end if;

  return jsonb_build_object('id', p_batch_id, 'status', 'open');
end;
$$;


