-- 8. RINGKASAN PER BATCH (untuk dashboard admin)
-- =============================================================================

create or replace function public.admin_batch_summary(p_batch_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'batch', (
      select jsonb_build_object(
        'id', id, 'label', label, 'note', note, 'status', status, 'created_at', created_at
      ) from public.batches where id = p_batch_id
    ),
    'total_orders', (select count(*) from public.orders where batch_id = p_batch_id),
    'total_items',  coalesce((select sum(item_count) from public.orders where batch_id = p_batch_id), 0),
    'revenue',      coalesce((select sum(total_price) from public.orders
                              where batch_id = p_batch_id
                                and status in ('accepted','ready','delivered')), 0),
    'by_flavor', coalesce((
      select jsonb_agg(
        jsonb_build_object('flavor_name', t.flavor_name, 'qty', t.qty)
        order by t.qty desc
      )
      from (
        select oi.flavor_name, sum(oi.quantity)::int as qty
        from public.order_items oi
        join public.orders o on o.id = oi.order_id
        where o.batch_id = p_batch_id
        group by oi.flavor_name
      ) t
    ), '[]'::jsonb),
    'by_delivery', coalesce((
      select jsonb_object_agg(delivery_method, cnt)
      from (
        select delivery_method, count(*)::int as cnt
        from public.orders where batch_id = p_batch_id
        group by delivery_method
      ) c
    ), '{}'::jsonb)
  );
end;
$$;


