-- =============================================================================
-- 2. BATCH PRE-ORDER
--    Pesanan dikelompokkan per "batch" supaya penjual bisa produksi bertahap.
-- =============================================================================

create table if not exists public.batches (
  id          bigint generated by default as identity primary key,
  label       text        not null,                       -- mis. "Batch 1"
  note        text        not null default '',
  status      text        not null default 'open' check (status in ('open','closed')),
  created_at  timestamptz not null default now(),
  closed_at   timestamptz
);

create index if not exists batches_status_idx on public.batches (status, created_at desc);

-- Setiap pesanan punya batch. Batch otomatis dibuat per hari.
alter table public.orders
  add column if not exists batch_id bigint references public.batches (id) on delete set null;

create index if not exists orders_batch_idx on public.orders (batch_id, created_at desc);

-- Backfill: pesanan lama dimasukan ke batch "Arsip".
insert into public.batches (label, note, status, created_at)
select 'Arsip', 'Pesanan sebelum fitur batch diperkenalkan', 'closed', now()
where not exists (select 1 from public.batches);

update public.orders
set batch_id = (select id from public.batches where label = 'Arsip' limit 1)
where batch_id is null;

-- Batch terbuka yang dipakai untuk pesanan baru.
create or replace function public.public_open_batch_id()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  select id into v_id
  from public.batches
  where status = 'open'
  order by created_at desc
  limit 1;

  if v_id is null then
    insert into public.batches (label, note)
    values (
      'Batch ' || to_char(now(), 'DD/MM'),
      'Dibuat otomatis ' || to_char(now(), 'DD MMM YYYY')
    )
    returning id into v_id;
  end if;

  return v_id;
end;
$$;


-- =============================================================================
-- 3. STOK GLOBAL — create_order
--    Stok satu angka untuk semua rasa. Kalau ada order 1 pcs, misal stok
--    20 -> 19 untuk semua rasa.
-- =============================================================================

create or replace function public.create_order(
  p_customer_name    text default '',
  p_phone            text default '',
  p_payment_method   text default 'cash',
  p_delivery_method  text default 'pickup',
  p_address          text default null,
  p_transfer_method  text default null,
  p_payment_proof    text default null,
  p_note             text default null,
  p_language         text default 'id',
  p_items            jsonb default '[]'::jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_settings   public.store_settings%rowtype;
  v_item       jsonb;
  v_flavor     public.flavors%rowtype;
  v_order_id   bigint;
  v_flavor_id  bigint;
  v_qty        integer;
  v_name       text;
  v_subtotal   integer := 0;
  v_count      integer := 0;
  v_items_ok   integer := 0;
  v_code       text;
  v_proof      text;
  v_batch_id   bigint;
begin
  -- ---------- validasi input ----------
  if p_customer_name is null or length(trim(p_customer_name)) < 2 then
    raise exception 'invalid_name' using errcode = '22023';
  end if;
  if length(trim(p_customer_name)) > 80 then
    raise exception 'name_too_long' using errcode = '22023';
  end if;

  if p_phone is null or length(public.normalize_phone(p_phone)) < 9 then
    raise exception 'invalid_phone' using errcode = '22023';
  end if;

  if p_payment_method not in ('transfer', 'cash') then
    raise exception 'invalid_payment_method' using errcode = '22023';
  end if;

  if p_delivery_method not in ('pickup', 'delivery') then
    raise exception 'invalid_delivery_method' using errcode = '22023';
  end if;

  if p_delivery_method = 'delivery' and coalesce(length(trim(p_address)), 0) < 5 then
    raise exception 'address_required' using errcode = '22023';
  end if;

  v_proof := nullif(trim(coalesce(p_payment_proof, '')), '');
  if p_payment_method = 'transfer' and v_proof is null then
    raise exception 'proof_required' using errcode = '22023';
  end if;

  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'empty_cart' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) > 30 then
    raise exception 'too_many_items' using errcode = '22023';
  end if;

  -- ---------- ambil settings ----------
  select * into v_settings from public.store_settings where id = 1 for update;
  if v_settings.id is null then
    raise exception 'settings_missing' using errcode = '22023';
  end if;
  if not v_settings.is_preorder_open then
    raise exception 'preorder_closed' using errcode = '22023';
  end if;

  -- ---------- validasi tiap rasa ----------
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_flavor_id := (v_item ->> 'flavor_id')::bigint;
    v_qty       := (v_item ->> 'quantity')::integer;

    if v_flavor_id is null or v_qty is null or v_qty < 1 or v_qty > v_settings.max_per_order then
      raise exception 'invalid_quantity' using errcode = '22023';
    end if;

    select * into v_flavor
    from public.flavors
    where id = v_flavor_id and is_active;

    if not found then
      raise exception 'flavor_unavailable' using errcode = '22023';
    end if;

    v_subtotal := v_subtotal + (v_flavor.price * v_qty);
    v_count    := v_count + v_qty;
    v_items_ok := v_items_ok + 1;
  end loop;

  if v_items_ok = 0 then
    raise exception 'empty_cart' using errcode = '22023';
  end if;

  if v_count < v_settings.min_order then
    raise exception 'below_min_order' using errcode = '22023';
  end if;

  -- ---------- cek & kurangi stok GLOBAL ----------
  -- Stok_settings baris sudah dikunci (for update) di atas, jadi dua pembeli
  -- yang memesan bersamaan tidak akan membuat stok minus.
  if v_settings.stock_enabled and v_count > v_settings.total_stock then
    raise exception 'insufficient_stock' using errcode = '22023';
  end if;

  if v_settings.stock_enabled then
    update public.store_settings
    set total_stock = total_stock - v_count
    where id = 1;
  end if;

  -- ---------- batch ----------
  v_batch_id := public.public_open_batch_id();

  -- ---------- generate kode pesanan ----------
  v_code := 'JS-' || to_char(now(), 'YYMMDD') || '-' || lpad(nextval('public.order_code_seq')::text, 3, '0');

  -- ---------- simpan pesanan ----------
  insert into public.orders (
    order_code, customer_name, phone, phone_normalized, delivery_method, address,
    payment_method, transfer_method, payment_proof_path, note,
    subtotal, delivery_fee, total_price, item_count, language, batch_id
  ) values (
    v_code,
    trim(p_customer_name),
    trim(p_phone),
    public.normalize_phone(p_phone),
    p_delivery_method,
    nullif(trim(coalesce(p_address, '')), ''),
    p_payment_method,
    nullif(trim(coalesce(p_transfer_method, '')), ''),
    v_proof,
    left(coalesce(p_note, ''), 500),
    v_subtotal,
    case when p_delivery_method = 'delivery' then v_settings.delivery_fee else 0 end,
    v_subtotal + case when p_delivery_method = 'delivery' then v_settings.delivery_fee else 0 end,
    v_count,
    case when p_language = 'en' then 'en' else 'id' end,
    v_batch_id
  )
  returning id into v_order_id;

  -- ---------- simpan item ----------
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_flavor_id := (v_item ->> 'flavor_id')::bigint;
    v_qty       := (v_item ->> 'quantity')::integer;

    select * into v_flavor from public.flavors where id = v_flavor_id;

    v_name := case when coalesce(p_language, 'id') = 'en' then v_flavor.name_en else v_flavor.name_id end;

    insert into public.order_items (
      order_id, flavor_id, flavor_slug, flavor_name, unit_price, quantity, line_total
    ) values (
      v_order_id, v_flavor.id, v_flavor.slug, v_name, v_flavor.price, v_qty, v_flavor.price * v_qty
    );
  end loop;

  return jsonb_build_object(
    'id', v_order_id,
    'order_code', v_code,
    'subtotal', v_subtotal,
    'delivery_fee', (select delivery_fee from public.orders where id = v_order_id),
    'total_price', (select total_price from public.orders where id = v_order_id),
    'remaining_stock', (select case when stock_enabled then total_stock else null end
                        from public.store_settings where id = 1)
  );
end;
$$;


-- =============================================================================
-- 4. STOK GLOBAL — admin_update_order_status
--    Tolak => stok global bertambah lagi.
-- =============================================================================

create or replace function public.admin_update_order_status(
  p_order_id   bigint,
  p_new_status text,
  p_admin_note text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if p_new_status not in ('pending','accepted','rejected','ready','delivered','cancelled') then
    raise exception 'invalid_status' using errcode = '22023';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'order_not_found' using errcode = 'P0002';
  end if;
  if v_order.status = p_new_status then
    raise exception 'status_unchanged' using errcode = '22023';
  end if;

  -- MENOLAK => stok global dikembalikan
  if p_new_status in ('rejected', 'cancelled') and v_order.stock_restored = false then
    update public.store_settings
    set total_stock = total_stock + v_order.item_count
    where id = 1 and stock_enabled;

    update public.orders set stock_restored = true where id = p_order_id;
  end if;

  -- Kembalikan pesanan ditolak ke menunggu => stok dipesan lagi
  if v_order.status in ('rejected','cancelled') and p_new_status = 'pending'
     and v_order.stock_restored = true then
    update public.store_settings s
    set total_stock = s.total_stock - v_order.item_count
    where s.id = 1
      and s.stock_enabled
      and s.total_stock >= v_order.item_count;

    if not found then
      raise exception 'insufficient_stock' using errcode = '22023';
    end if;

    update public.orders set stock_restored = false where id = p_order_id;
  end if;

  update public.orders
  set status = p_new_status,
      admin_note = coalesce(nullif(trim(coalesce(p_admin_note, '')), ''), admin_note)
  where id = p_order_id;

  return jsonb_build_object(
    'id', p_order_id,
    'status', p_new_status,
    'total_stock', (select case when stock_enabled then total_stock else null end
                    from public.store_settings where id = 1)
  );
end;
$$;


