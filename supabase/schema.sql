-- Bootstrap admin: user pertama yang mendaftar otomatis menjadi admin.
create or replace function public.handle_first_user_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.admins) then
    insert into public.admins (user_id, email, full_name)
    values (
      new.id,
      new.email,
      coalesce(new.raw_user_meta_data ->> 'full_name', '')
    );
  end if;
  return new;
end;
$$;

drop trigger if exists on_first_user_created on auth.users;
create trigger on_first_user_created
after insert on auth.users
for each row execute function public.handle_first_user_admin();

