-- =============================================================================
-- 9. PERBAIKAN: RLS pada schema auth
-- -----------------------------------------------------------------------------
-- Tabel di schema `auth` memakai Row Level Security. GoTrue (login & daftar
-- user) membaca/menulis tabel tersebut sebagai role `supabase_auth_admin`.
-- Normally role itu punya BYPASSRLS; kalau hilang, SEMUA login gagal dengan
-- error "Database error querying schema" (HTTP 500).
--
-- `alter role` tidak diizinkan di sini (role reserved, butuh superuser), jadi
-- kita beri policy permisif untuk role tersebut. Efeknya sama dengan
-- BYPASSRLS khusus untuk tabel auth.
-- =============================================================================
do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'instances',
    'users', 'identities', 'sessions', 'refresh_tokens', 'flow_state',
    'mfa_amr_claims', 'mfa_challenges', 'mfa_factors',
    'mfa_recovery_code_sets', 'mfa_recovery_codes',
    'one_time_tokens', 'audit_log_entries', 'sso_domains', 'sso_providers',
    'saml_providers', 'saml_relay_states', 'oauth_authorizations',
    'oauth_client_states', 'oauth_clients', 'oauth_consents',
    'webauthn_challenges', 'webauthn_credentials', 'custom_oauth_providers'
  ] loop
    -- Some auth tables are owned by another role; skip them quietly so this
    -- script still succeeds on projects where we don't own every table.
    begin
      execute format('drop policy if exists gotrue_full_access on auth.%I', v_table);
      execute format(
        'create policy gotrue_full_access on auth.%I
           for all to supabase_auth_admin using (true) with check (true)',
        v_table
      );
    exception when insufficient_privilege then
      raise notice 'Tabel auth.% owned by role lain, dilewati.', v_table;
    end;
  end loop;
end
$$;

