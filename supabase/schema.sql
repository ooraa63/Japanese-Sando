-- Produk / rasa sando -------------------------------------------------------
create table if not exists public.flavors (
  id              bigint generated by default as identity primary key,
  slug            text        not null unique,
  name_id         text        not null,
  name_en         text        not null,
  desc_id         text        not null default '',
  desc_en         text        not null default '',
  price           integer     not null check (price >= 0),
  image_url       text,
  is_active       boolean     not null default true,   -- tampil / tidak di etalase
  is_featured     boolean     not null default false,  --/Unggulan di landing page
  stock_enabled   boolean     not null default true,   -- false = stok tak terbatas
  stock           integer     not null default 0 check (stock >= 0),
  sort_order      integer     not null default 0,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- Pengaturan toko (baris tunggal, id = 1) ----------------------------------
create table if not exists public.store_settings (
  id                  smallint    primary key default 1 check (id = 1),
  store_name          text        not null default 'Japanese Sando',
  tagline_id          text        not null default 'Roti Sederhana, Rasa Luar Biasa',
  tagline_en          text        not null default 'Simple Bread, Extraordinary Flavors',
  description_id      text        not null default '',
  description_en      text        not null default '',
  whatsapp            text        not null default '',  -- format internasional, mis. 6281234567890
  address             text        not null default '',
  maps_url            text        not null default '',
  instagram           text        not null default '',
  tiktok              text        not null default '',
  hours_id            text        not null default '',
  hours_en            text        not null default '',
  deadline_id         text        not null default 'Pesanan ditutup pukul 21.00 WIB',
  deadline_en         text        not null default 'Orders close at 9:00 PM (GMT+7)',
  min_order           integer     not null default 1 check (min_order >= 1),
  max_per_order       integer     not null default 20 check (max_per_order >= 1),
  delivery_fee        integer     not null default 0 check (delivery_fee >= 0),
  free_shipping_min   integer     not null default 0 check (free_shipping_min >= 0),
  bank_accounts       jsonb       not null default '[]'::jsonb,
  qris_enabled        boolean     not null default false,
  qris_image_url      text,
  announcement_id     text        not null default '',
  announcement_en     text        not null default '',
  is_preorder_open    boolean     not null default true,
  updated_at          timestamptz not null default now()
);

-- Pesanan -------------------------------------------------------------------
create table if not exists public.orders (
  id                  bigint generated by default as identity primary key,
  order_code          text        not null unique,
  customer_name       text        not null,
  phone               text        not null,
  phone_normalized    text        not null,
  delivery_method     text        not null default 'pickup'
                      check (delivery_method in ('pickup','delivery')),
  address             text,
  payment_method      text        not null check (payment_method in ('transfer','cash')),
  transfer_method     text,       -- bank / ewallet / qris (opsional)
  payment_proof_path  text,
  note                text        not null default '',
  admin_note          text        not null default '',
  subtotal            integer     not null default 0,
  delivery_fee        integer     not null default 0,
  total_price         integer     not null default 0,
  item_count          integer     not null default 0,
  status              text        not null default 'pending'
                      check (status in ('pending','accepted','rejected','ready','delivered','cancelled')),
  stock_restored      boolean     not null default false,
  language            text        not null default 'id',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_phone_idx      on public.orders (phone_normalized);
create index if not exists orders_code_idx       on public.orders (order_code);

-- Item pesanan (snapshot harga & nama saat order dibuat) --------------------
create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  order_id      bigint    not null references public.orders (id) on delete cascade,
  flavor_id     bigint    references public.flavors (id) on delete set null,
  flavor_slug   text      not null,
  flavor_name   text      not null,
  unit_price    integer   not null,
  quantity      integer   not null check (quantity > 0),
  line_total    integer   not null,
  created_at    timestamptz not null default now()
);

create index if not exists order_items_order_idx on public.order_items (order_id);

-- Admin / user aplikasi -----------------------------------------------------
create table if not exists public.admins (
  user_id     uuid        primary key references auth.users (id) on delete cascade,
  email       text        not null,
  full_name   text        not null default '',
  role        text        not null default 'owner' check (role in ('owner','staff')),
  is_active   boolean     not null default true,
  created_at  timestamptz not null default now()
);

-- Riwayat perubahan stok (audit trail, opsional tapi berguna) ---------------
create table if not exists public.stock_logs (
  id          bigint generated by default as identity primary key,
  flavor_id   bigint    not null references public.flavors (id) on delete cascade,
  delta       integer   not null,
  reason      text      not null default 'manual',
  note        text      not null default '',
  actor_id    uuid,
  created_at  timestamptz not null default now()
);

create index if not exists stock_logs_flavor_idx on public.stock_logs (flavor_id, created_at desc);

