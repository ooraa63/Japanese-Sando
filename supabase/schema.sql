-- Daftar pesanan untuk dashboard ---------------------------------------------
create or replace function public.admin_list_orders(
  p_status  text default null,
  p_search  text default null,
  p_limit   integer default 50,
  p_offset  integer default 0
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  return (
    with filtered as (
      select o.*
      from public.orders o
      where (p_status is null or o.status = p_status)
        and (
          p_search is null
          or btrim(p_search) = ''
          or o.order_code ilike '%' || p_search || '%'
          or o.customer_name ilike '%' || p_search || '%'
          or o.phone ilike '%' || p_search || '%'
        )
      order by o.created_at desc
      limit greatest(1, least(p_limit, 200))
      offset greatest(0, p_offset)
    )
    select jsonb_build_object(
      'orders', coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', f.id,
            'order_code', f.order_code,
            'customer_name', f.customer_name,
            'phone', f.phone,
            'delivery_method', f.delivery_method,
            'address', f.address,
            'payment_method', f.payment_method,
            'transfer_method', f.transfer_method,
            'payment_proof_path', f.payment_proof_path,
            'note', f.note,
            'admin_note', f.admin_note,
            'subtotal', f.subtotal,
            'delivery_fee', f.delivery_fee,
            'total_price', f.total_price,
            'item_count', f.item_count,
            'status', f.status,
            'language', f.language,
            'created_at', f.created_at,
            'updated_at', f.updated_at,
            'items', coalesce((
              select jsonb_agg(jsonb_build_object(
                'flavor_name', oi.flavor_name,
                'quantity', oi.quantity,
                'unit_price', oi.unit_price,
                'line_total', oi.line_total
              ) order by oi.id)
              from public.order_items oi where oi.order_id = f.id
            ), '[]'::jsonb)
          ) order by f.created_at desc
        ) from filtered f
      ), '[]'::jsonb),
      'total', (select count(*) from filtered)
    )
  );
end;
$$;

-- Ubah status pesanan (+/âˆ’ stok otomatis) -----------------------------------
create or replace function public.admin_update_order_status(
  p_order_id   bigint,
  p_new_status text,
  p_admin_note text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if p_new_status not in ('pending','accepted','rejected','ready','delivered','cancelled') then
    raise exception 'invalid_status' using errcode = '22023';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'order_not_found' using errcode = 'P0002';
  end if;
  if v_order.status = p_new_status then
    raise exception 'status_unchanged' using errcode = '22023';
  end if;

  -- MENOLAK => stok dikembalikan ke rak.
  -- (Status "cancelled" tidak lagi dipakai penjual, tapi pesanan lama
  --  berstatus itu tetap bisa dikembalikan agar tidak menggantung.)
  if p_new_status in ('rejected', 'cancelled') and v_order.stock_restored = false then
    update public.flavors f
    set stock = f.stock + it.qty
    from (
      select oi.flavor_id, sum(oi.quantity)::int as qty
      from public.order_items oi
      where oi.order_id = p_order_id and oi.flavor_id is not null
      group by oi.flavor_id
    ) it
    where f.id = it.flavor_id and f.stock_enabled;

    update public.orders set stock_restored = true where id = p_order_id;
  end if;

  -- Kembalikan pesanan yang ditolak ke status menunggu => stok dipesan lagi
  -- (gagal kalau stok meantime sudah habis dipakai pesanan lain).
  if v_order.status in ('rejected', 'cancelled') and p_new_status = 'pending' and v_order.stock_restored = true then
    update public.flavors f
    set stock = f.stock - it.qty
    from (
      select oi.flavor_id, sum(oi.quantity)::int as qty
      from public.order_items oi
      where oi.order_id = p_order_id and oi.flavor_id is not null
      group by oi.flavor_id
    ) it
    where f.id = it.flavor_id and f.stock_enabled
      and f.stock >= it.qty;

    if not found then
      raise exception 'insufficient_stock' using errcode = '22023';
    end if;

    update public.orders set stock_restored = false where id = p_order_id;
  end if;

  update public.orders
  set status = p_new_status,
      admin_note = coalesce(nullif(trim(coalesce(p_admin_note, '')), ''), admin_note)
  where id = p_order_id;

  return jsonb_build_object('id', p_order_id, 'status', p_new_status);
end;
$$;

