create or replace function public.normalize_phone(p_phone text)
returns text
language plpgsql
immutable
as $$
declare
  v text;
begin
  v := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  if length(v) = 0 then
    return v;
  end if;
  if v like '62%' then
    return v;                              -- sudah format internasional
  end if;
  if v like '0%' then
    return '62' || substring(v from 2);     -- 0812... -> 62812...
  end if;
  return v;
end;
$$;

