-- =============================================================================
-- 4. FUNGSI PUBLIK â€” BUAT PESANAN (dipanggil pembeli, tanpa login)
--    Harga SELALU diambil dari server, tidak pernah dipercaya dari klien.
-- =============================================================================
create or replace function public.create_order(
  p_customer_name    text default '',
  p_phone            text default '',
  p_payment_method   text default 'cash',
  p_delivery_method  text default 'pickup',
  p_address          text default null,
  p_transfer_method  text default null,
  p_payment_proof    text default null,
  p_note             text default null,
  p_language         text default 'id',
  p_items            jsonb default '[]'::jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_settings   public.store_settings%rowtype;
  v_item       jsonb;
  v_flavor     public.flavors%rowtype;
  v_order_id   bigint;
  v_flavor_id  bigint;
  v_qty        integer;
  v_name       text;
  v_subtotal   integer := 0;
  v_count      integer := 0;
  v_items_ok   integer := 0;
  v_code       text;
  v_proof      text;
begin
  -- ---------- validasi input ----------
  if p_customer_name is null or length(trim(p_customer_name)) < 2 then
    raise exception 'invalid_name' using errcode = '22023';
  end if;
  if length(trim(p_customer_name)) > 80 then
    raise exception 'name_too_long' using errcode = '22023';
  end if;

  if p_phone is null or length(public.normalize_phone(p_phone)) < 9 then
    raise exception 'invalid_phone' using errcode = '22023';
  end if;

  if p_payment_method not in ('transfer', 'cash') then
    raise exception 'invalid_payment_method' using errcode = '22023';
  end if;

  if p_delivery_method not in ('pickup', 'delivery') then
    raise exception 'invalid_delivery_method' using errcode = '22023';
  end if;

  if p_delivery_method = 'delivery' and coalesce(length(trim(p_address)), 0) < 5 then
    raise exception 'address_required' using errcode = '22023';
  end if;

  v_proof := nullif(trim(coalesce(p_payment_proof, '')), '');
  if p_payment_method = 'transfer' and v_proof is null then
    raise exception 'proof_required' using errcode = '22023';
  end if;

  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'empty_cart' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) > 30 then
    raise exception 'too_many_items' using errcode = '22023';
  end if;

  -- ---------- ambil settings ----------
  select * into v_settings from public.store_settings where id = 1;
  if v_settings.id is null then
    raise exception 'settings_missing' using errcode = '22023';
  end if;
  if not v_settings.is_preorder_open then
    raise exception 'preorder_closed' using errcode = '22023';
  end if;

  -- ---------- validasi + kunci tiap rasa ----------
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_flavor_id := (v_item ->> 'flavor_id')::bigint;
    v_qty       := (v_item ->> 'quantity')::integer;

    if v_flavor_id is null or v_qty is null or v_qty < 1 or v_qty > v_settings.max_per_order then
      raise exception 'invalid_quantity' using errcode = '22023';
    end if;

    select * into v_flavor
    from public.flavors
    where id = v_flavor_id and is_active
    for update;                                   -- kunci baris, mencegah stok bentrok

    if not found then
      raise exception 'flavor_unavailable' using errcode = '22023';
    end if;

    if v_flavor.stock_enabled and v_flavor.stock < v_qty then
      raise exception 'insufficient_stock' using errcode = '22023';
    end if;

    v_subtotal := v_subtotal + (v_flavor.price * v_qty);
    v_count    := v_count + v_qty;
    v_items_ok := v_items_ok + 1;
  end loop;

  if v_items_ok = 0 then
    raise exception 'empty_cart' using errcode = '22023';
  end if;

  if v_count < v_settings.min_order then
    raise exception 'below_min_order' using errcode = '22023';
  end if;

  -- ---------- generate kode pesanan (sequence, selalu unik) ----------
  v_code := 'JS-' || to_char(now(), 'YYMMDD') || '-' || lpad(nextval('public.order_code_seq')::text, 3, '0');

  -- ---------- simpan pesanan ----------
  insert into public.orders (
    order_code, customer_name, phone, phone_normalized, delivery_method, address,
    payment_method, transfer_method, payment_proof_path, note,
    subtotal, delivery_fee, total_price, item_count, language
  ) values (
    v_code,
    trim(p_customer_name),
    trim(p_phone),
    public.normalize_phone(p_phone),
    p_delivery_method,
    nullif(trim(coalesce(p_address, '')), ''),
    p_payment_method,
    nullif(trim(coalesce(p_transfer_method, '')), ''),
    v_proof,
    left(coalesce(p_note, ''), 500),
    v_subtotal,
    case when p_delivery_method = 'delivery' then v_settings.delivery_fee else 0 end,
    v_subtotal + case when p_delivery_method = 'delivery' then v_settings.delivery_fee else 0 end,
    v_count,
    case when p_language = 'en' then 'en' else 'id' end
  )
  returning id into v_order_id;

  -- ---------- simpan item ----------
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_flavor_id := (v_item ->> 'flavor_id')::bigint;
    v_qty       := (v_item ->> 'quantity')::integer;

    select * into v_flavor from public.flavors where id = v_flavor_id;

    v_name := case when coalesce(p_language, 'id') = 'en' then v_flavor.name_en else v_flavor.name_id end;

    insert into public.order_items (
      order_id, flavor_id, flavor_slug, flavor_name, unit_price, quantity, line_total
    ) values (
      v_order_id, v_flavor.id, v_flavor.slug, v_name, v_flavor.price, v_qty, v_flavor.price * v_qty
    );
  end loop;

  -- ---------- kurangi stok ----------
  -- Stok langsung berkurang begitu pembeli mengirim pre-order, tanpa menunggu
  -- keputusan admin. Ini mencegah produk terjual habis padahal pesanan sudah
  -- masuk.
  --
  -- Kalau nanti admin MENOLAK pesanan ini, stok dikembalikan lagi oleh
  -- admin_update_order_status() (lihat blok "tolak => stok dikembalikan").
  --
  -- Produk dengan stock_enabled = false (stok tak terbatas) tidak terpengaruh.
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_flavor_id := (v_item ->> 'flavor_id')::bigint;
    v_qty       := (v_item ->> 'quantity')::integer;

    update public.flavors
    set stock = stock - v_qty
    where id = v_flavor_id and stock_enabled;
  end loop;

  -- ---------- generate kode pesanan sudah dilakukan di atas ----------

  return jsonb_build_object(
    'id', v_order_id,
    'order_code', v_code,
    'subtotal', v_subtotal,
    'delivery_fee', (select delivery_fee from public.orders where id = v_order_id),
    'total_price', (select total_price from public.orders where id = v_order_id)
  );
end;
$$;

-- Lacak pesanan dengan kode + nomor telepon ---------------------------------
create or replace function public.track_order(p_code text, p_phone text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_items jsonb;
begin
  select * into v_order
  from public.orders
  where upper(order_code) = upper(trim(coalesce(p_code, '')))
    and phone_normalized = public.normalize_phone(p_phone)
  limit 1;

  if not found then
    return null;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'flavor_name', flavor_name,
    'quantity', quantity,
    'unit_price', unit_price,
    'line_total', line_total
  ) order by id), '[]'::jsonb)
  into v_items
  from public.order_items where order_id = v_order.id;

  return jsonb_build_object(
    'order_code', v_order.order_code,
    'customer_name', v_order.customer_name,
    'phone', v_order.phone,
    'status', v_order.status,
    'delivery_method', v_order.delivery_method,
    'address', v_order.address,
    'payment_method', v_order.payment_method,
    'note', v_order.note,
    'subtotal', v_order.subtotal,
    'delivery_fee', v_order.delivery_fee,
    'total_price', v_order.total_price,
    'item_count', v_order.item_count,
    'language', v_order.language,
    'created_at', v_order.created_at,
    'updated_at', v_order.updated_at,
    'items', v_items
  );
end;
$$;

