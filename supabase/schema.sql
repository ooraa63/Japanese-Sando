-- Simpan produk (id ada = update, id kosong = insert baru) -------------------
create or replace function public.admin_save_flavor(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id     bigint := nullif(p_payload ->> 'id', '')::bigint;
  v_slug   text;
  v_name   text;
  v_exists boolean;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  v_name := btrim(coalesce(p_payload ->> 'name_id', ''));
  if v_name = '' then
    raise exception 'invalid_name' using errcode = '22023';
  end if;

  v_slug := lower(regexp_replace(trim(coalesce(p_payload ->> 'slug', v_name)), '[^a-zA-Z0-9]+', '-', 'g'));
  v_slug := trim(both '-' from v_slug);
  if v_slug = '' then
    v_slug := 'item-' || substr(md5(random()::text), 1, 8);
  end if;

  -- Hindari bentrok slug dengan produk lain
  if v_id is not null then
    select exists (select 1 from public.flavors where slug = v_slug and id <> v_id) into v_exists;
  else
    select exists (select 1 from public.flavors where slug = v_slug) into v_exists;
  end if;
  if v_exists then
    v_slug := v_slug || '-' || substr(md5(random()::text), 1, 4);
  end if;

  if coalesce((p_payload ->> 'price')::integer, -1) < 0 then
    raise exception 'invalid_price' using errcode = '22023';
  end if;

  if v_id is not null then
    update public.flavors set
      slug          = v_slug,
      name_id       = v_name,
      name_en       = coalesce(nullif(btrim(p_payload ->> 'name_en'), ''), v_name),
      desc_id       = coalesce(p_payload ->> 'desc_id', ''),
      desc_en       = coalesce(p_payload ->> 'desc_en', ''),
      price         = (p_payload ->> 'price')::integer,
      image_url     = nullif(trim(coalesce(p_payload ->> 'image_url', '')), ''),
      is_active     = coalesce((p_payload ->> 'is_active')::boolean, true),
      is_featured   = coalesce((p_payload ->> 'is_featured')::boolean, false),
      stock_enabled = coalesce((p_payload ->> 'stock_enabled')::boolean, true),
      stock         = greatest(0, coalesce((p_payload ->> 'stock')::integer, 0)),
      sort_order    = coalesce((p_payload ->> 'sort_order')::integer, 0)
    where id = v_id
    returning id into v_id;
  else
    insert into public.flavors (
      slug, name_id, name_en, desc_id, desc_en, price, image_url,
      is_active, is_featured, stock_enabled, stock, sort_order
    ) values (
      v_slug,
      v_name,
      coalesce(nullif(btrim(p_payload ->> 'name_en'), ''), v_name),
      coalesce(p_payload ->> 'desc_id', ''),
      coalesce(p_payload ->> 'desc_en', ''),
      (p_payload ->> 'price')::integer,
      nullif(trim(coalesce(p_payload ->> 'image_url', '')), ''),
      coalesce((p_payload ->> 'is_active')::boolean, true),
      coalesce((p_payload ->> 'is_featured')::boolean, false),
      coalesce((p_payload ->> 'stock_enabled')::boolean, true),
      greatest(0, coalesce((p_payload ->> 'stock')::integer, 0)),
      coalesce((p_payload ->> 'sort_order')::integer, 0)
    )
    returning id into v_id;
  end if;

  if v_id is null then
    raise exception 'invalid_payload' using errcode = '22023';
  end if;

  return jsonb_build_object('id', v_id, 'slug', v_slug);
end;
$$;

-- Hapus produk --------------------------------------------------------------
create or replace function public.admin_delete_flavor(p_flavor_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if exists (
    select 1 from public.order_items
    where flavor_id = p_flavor_id
      and order_id in (select id from public.orders where status in ('pending','accepted','ready'))
  ) then
    -- ada pesanan aktif -> nonaktifkan saja, jangan dihapus
    update public.flavors set is_active = false where id = p_flavor_id;
    return jsonb_build_object('deleted', false, 'deactivated', true);
  end if;

  delete from public.flavors where id = p_flavor_id;
  return jsonb_build_object('deleted', true, 'deactivated', false);
end;
$$;

-- Atur stok -----------------------------------------------------------------
create or replace function public.admin_set_stock(
  p_flavor_id bigint,
  p_stock     integer,
  p_note      text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old integer;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;
  if p_stock is null or p_stock < 0 then
    raise exception 'invalid_stock' using errcode = '22023';
  end if;

  select stock into v_old from public.flavors where id = p_flavor_id for update;
  if not found then
    raise exception 'flavor_not_found' using errcode = 'P0002';
  end if;

  update public.flavors set stock = p_stock where id = p_flavor_id;

  insert into public.stock_logs (flavor_id, delta, reason, note, actor_id)
  values (p_flavor_id, p_stock - v_old, 'manual', coalesce(p_note, ''), auth.uid());

  return jsonb_build_object('id', p_flavor_id, 'stock', p_stock);
end;
$$;

