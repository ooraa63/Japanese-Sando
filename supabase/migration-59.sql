            'price', b.price,
            'compare_price', b.compare_price,
            'required_qty', b.required_qty,
            'image_url', b.image_url,
            'is_active', b.is_active,
            'is_featured', b.is_featured,
            'sort_order', b.sort_order,
            'is_fixed', b.is_fixed,
            'flavor_ids', coalesce((select jsonb_agg(bf.flavor_id order by bf.flavor_id)
                                    from public.bundle_flavors bf where bf.bundle_id = b.id),
                                   '[]'::jsonb),
            'slots', public.bundle_slot_groups(b.id)
          ) order by b.sort_order, b.id
        )
        from public.bundles b
        where (b.category_id = c.id or b.category_id is null) and b.is_active
      ), '[]'::jsonb)
    ) as j
    from public.categories c
    where c.is_active
  ),
  standalone_bundles as (
    select jsonb_agg(
      jsonb_build_object(
        'id', b.id,
        'category_id', b.category_id,
        'slug', b.slug,
        'name_id', b.name_id,
        'name_en', b.name_en,
        'desc_id', b.desc_id,
        'desc_en', b.desc_en,
        'price', b.price,
        'compare_price', b.compare_price,
        'required_qty', b.required_qty,
        'image_url', b.image_url,
        'is_active', b.is_active,
        'is_featured', b.is_featured,
        'sort_order', b.sort_order,
        'is_fixed', b.is_fixed,
        'flavor_ids', coalesce((select jsonb_agg(bf.flavor_id order by bf.flavor_id)
                                from public.bundle_flavors bf where bf.bundle_id = b.id),
                               '[]'::jsonb),
        'slots', public.bundle_slot_groups(b.id)
      ) order by b.sort_order, b.id
    ) as j
    from public.bundles b
    where b.category_id is null and b.is_active
  )
  select jsonb_build_object(
    'categories', coalesce((select jsonb_agg(j order by (j->>'sort_order')::int, (j->>'id')::int) from cats), '[]'::jsonb),
    'bundles', coalesce((select j from standalone_bundles), '[]'::jsonb)
  );
$fn$;

grant execute on function public.public_menu()
  to postgres, authenticated, service_role;

-- ============================================================ 6. SIMPAN PAKET

create or replace function public.admin_save_bundle(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$

declare
  v_id        bigint := nullif(p_payload ->> 'id', '')::bigint;
  v_slug      text;
  v_name      text;
  v_price     integer;
  v_compare   integer;
  v_qty       integer;
  v_is_fixed  boolean;
  v_flavor_cnt integer;
  -- migration-59: daftar pilihan per paket.
  v_slots      jsonb;
  v_slot_cnt   integer;
  v_bad        integer;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  v_name := btrim(coalesce(p_payload ->> 'name_id', ''));
  if v_name = '' then
    raise exception 'invalid_name' using errcode = '22023';
  end if;

  v_price := nullif(p_payload ->> 'price', '')::integer;
  if v_price is null or v_price < 0 then
    raise exception 'invalid_price' using errcode = '22023';
  end if;

  -- Harga coret hanya valid kalau lebih besar dari harga jual.
  v_compare := nullif(p_payload ->> 'compare_price', '')::integer;
  if v_compare is not null and v_compare <= v_price then
    v_compare := null;
  end if;

  v_qty := nullif(p_payload ->> 'required_qty', '')::integer;
  if v_qty is null or v_qty < 1 then
    raise exception 'invalid_quantity' using errcode = '22023';
  end if;

  v_is_fixed := coalesce((p_payload ->> 'is_fixed')::boolean, false);
  -- migration-59: `slots` ada = mode PILIHAN. `slots` tidak ada = paket
  -- ini tidak memakai mode baru, jadi baris `bundle_slots`-nya tidak
  -- boleh disentuh. `slots: []` = kembalikan ke mode biasa.
  v_slots := p_payload -> 'slots';

  v_slug := trim(both '-' from
    regexp_replace(lower(coalesce(nullif(btrim(coalesce(p_payload ->> 'slug', '')), ''), v_name)),
                   '[^a-z0-9]+', '-', 'g'));
  if v_slug = '' then
    v_slug := 'bundle-' || substr(md5(random()::text), 1, 6);
  end if;

  if v_id is not null then
    if exists (select 1 from public.bundles where slug = v_slug and id <> v_id) then
      v_slug := v_slug || '-' || substr(md5(random()::text), 1, 4);
    end if;

    update public.bundles set
      category_id  = nullif(p_payload ->> 'category_id', '')::bigint,
      slug         = v_slug,
      name_id      = v_name,
      name_en      = coalesce(nullif(btrim(coalesce(p_payload ->> 'name_en', '')), ''), v_name),
      desc_id      = coalesce(p_payload ->> 'desc_id', ''),
      desc_en      = coalesce(p_payload ->> 'desc_en', ''),
      price        = v_price,
      compare_price = case when p_payload ? 'compare_price' then v_compare
                           else compare_price end,
      required_qty = v_qty,
      image_url    = case when p_payload ? 'image_url'
                          then nullif(trim(coalesce(p_payload ->> 'image_url', '')), '')
                          else image_url end,
      is_active    = coalesce((p_payload ->> 'is_active')::boolean, true),
      is_featured  = coalesce((p_payload ->> 'is_featured')::boolean, false),
      sort_order   = coalesce((p_payload ->> 'sort_order')::integer, 0),
      is_fixed     = case when p_payload ? 'is_fixed' then v_is_fixed else is_fixed end
    where id = v_id
    returning id into v_id;
  else
    if exists (select 1 from public.bundles where slug = v_slug) then
      raise exception 'slug_taken' using errcode = '22023';
    end if;

    insert into public.bundles (
      category_id, slug, name_id, name_en, desc_id, desc_en,
      price, compare_price, required_qty, image_url, is_active, is_featured,
      sort_order, is_fixed
    ) values (
      nullif(p_payload ->> 'category_id', '')::bigint,
      v_slug, v_name,
      coalesce(nullif(btrim(coalesce(p_payload ->> 'name_en', '')), ''), v_name),
      coalesce(p_payload ->> 'desc_id', ''),
      coalesce(p_payload ->> 'desc_en', ''),
      v_price, v_compare, v_qty,
      nullif(trim(coalesce(p_payload ->> 'image_url', '')), ''),
      coalesce((p_payload ->> 'is_active')::boolean, true),
      coalesce((p_payload ->> 'is_featured')::boolean, false),
      coalesce((p_payload ->> 'sort_order')::integer, 0),
      v_is_fixed
    )
    returning id into v_id;
  end if;

  if v_id is null then
    raise exception 'invalid_payload' using errcode = '22023';
  end if;

  -- Isi bundle dipilih PENJUAL lewat daftar rasa, bukan kategori tetap.
  -- Daftar kosong = semua rasa aktif yang boleh dipakai (bundle berdiri sendiri).
  if p_payload ? 'flavor_ids' and jsonb_typeof(p_payload -> 'flavor_ids') = 'array' then
    delete from public.bundle_flavors where bundle_id = v_id;
    insert into public.bundle_flavors (bundle_id, flavor_id)
    select distinct v_id, f.id
    from jsonb_array_elements_text(coalesce(p_payload -> 'flavor_ids', '[]'::jsonb)) as x(value)
    join public.flavors f on f.id::text = btrim(x.value)
    on conflict do nothing;
  end if;

  -- (migration-59) Mode PILIHAN: tiap pilihan punya daftar rasa sendiri.
  -- Dijalankan kalau payload mengirim kunci `slots`.
  --
  -- Validasi dilakukan TERLEBIH DAHULU, sebelum baris lama dihapus, supaya
  -- paket yang gagal disimpan tidak ikut kehilangan konfigasinya.
  if jsonb_typeof(v_slots) = 'array' then
    if jsonb_array_length(v_slots) > 10 then
      raise exception 'invalid_bundle_slots' using errcode = '22023';
    end if;

    -- Tiap pilihan wajib punya minimal satu rasa. Pilihan kosong berarti
    -- pembeli tidak bisa menyelesaikan paketnya sendiri.
    select count(*) into v_bad
    from jsonb_array_elements(v_slots) e(item)
    where jsonb_typeof(e.item) is distinct from 'object'
       or jsonb_typeof(e.item -> 'flavor_ids') is distinct from 'array'
       or jsonb_array_length(e.item -> 'flavor_ids') = 0;
    if v_bad > 0 then
      raise exception 'invalid_bundle_slots' using errcode = '22023';
    end if;

    -- Id rasa harus benar-benar ada. Daftar yang diam-diam dropping id
    -- salah akan membuat admin mengira rasa itu sudah masuk padahal
    -- pembeli tidak pernah bisa memilihnya.
    select count(*) into v_bad
    from jsonb_array_elements(v_slots) e(item)
    cross join lateral jsonb_array_elements_text(
      case when jsonb_typeof(e.item -> 'flavor_ids') = 'array'
           then e.item -> 'flavor_ids' else '[]'::jsonb end
    ) f(value)
    where btrim(f.value) !~ '^[0-9]+$'
       or not exists (select 1 from public.flavors fl where fl.id::text = btrim(f.value));
    if v_bad > 0 then
      raise exception 'invalid_bundle_slots' using errcode = '22023';
    end if;

    select count(*) into v_slot_cnt from jsonb_array_elements(v_slots);

    -- Ganti seluruh pilihan lama. `slot_index` diambil dari posisi
    -- array, jadi tidak pernah bentrok dan selalu 1..N tanpa lubang.
    delete from public.bundle_slot_flavors bsf
     where bsf.bundle_slot_id in (select id from public.bundle_slots where bundle_id = v_id);
    delete from public.bundle_slots where bundle_id = v_id;

    insert into public.bundle_slots (bundle_id, slot_index, label_id, label_en)
    select v_id,
           s.ord::int,
           coalesce(nullif(btrim(coalesce(s.item ->> 'label_id', '')), ''), 'Pilihan ' || s.ord::text),
           coalesce(nullif(btrim(coalesce(s.item ->> 'label_en', '')), ''), 'Choice ' || s.ord::text)
    from jsonb_array_elements(v_slots) with ordinality as s(item, ord);

    insert into public.bundle_slot_flavors (bundle_slot_id, flavor_id)
    select bs.id, fl.id
    from jsonb_array_elements(v_slots) with ordinality as s(item, ord)
    join public.bundle_slots bs
      on bs.bundle_id = v_id and bs.slot_index = s.ord::int
    cross join lateral jsonb_array_elements_text(s.item -> 'flavor_ids') f(value)
    join public.flavors fl on fl.id::text = btrim(f.value)
    on conflict do nothing;

    -- Dua hal yang harus selalu jalan bareng:
    --   required_qty = jumlah pilihan (dibaca create_order untuk
    --   mengecek panjang `slots` dan membagi harga paket),
    --   is_fixed = false, karena paket yang punya pilihan berubah dan
    --   paket terkunci jelas bukan hal yang sama.
    -- Dipaksa, bukan ditolak, supaya paket yang tersimpan selalu bisa
    -- dibeli. UI admin tidak pernah mengirim keduanya sekaligus.
    update public.bundles
       set required_qty = v_slot_cnt,
           is_fixed = false
     where id = v_id;
    v_qty := v_slot_cnt;
  end if;

  -- (migration-54) Mode terkunci: daftar rasa adalah ISI paket, jadi
  -- jumlahnya harus sama persis dengan required_qty. Kalau tidak, paket yang
  -- tersimpan tidak akan pernah bisa dibeli — pembeli tidak pernah bisa
  -- terkunci di jumlah rasa, padahal daftarnya sendiri lebih pendek dari itu.
  v_is_fixed := coalesce((select is_fixed from public.bundles where id = v_id), false);
  if v_is_fixed then
    select count(*) into v_flavor_cnt
    from public.bundle_flavors bf
    join public.flavors f on f.id = bf.flavor_id and f.is_active
    where bf.bundle_id = v_id;

    if v_flavor_cnt <> v_qty then
      raise exception 'invalid_bundle_fixed' using errcode = '22023';
    end if;
  end if;

  return jsonb_build_object('id', v_id, 'slug', v_slug);
end;
