-- =============================================================================
--  MIGRASI 59 --
--  Paket dengan pilihan terpisah: tiap "pilihan" punya daftar rasa sendiri
-- =============================================================================
--
--  Steven 15-10-2026:
--
--    "misal ada paket 2, saya bisa menentukan pilihan 1 antara apa aja
--     lalu pilihan 2 apa aja begitu"
--
--  Contoh konkret dari Steven:
--
--    Paket "Sando 2" dengan harga di antara Rp22.000 dan Rp18.000, mis. Rp20.000:
--      - Pilihan 1 : Egg Mayo atau Chicken Curry Katsu   (harga 22.000)
--      - Pilihan 2 : salah satu dari 5 rasa manis           (harga 18.000)
--
--  Yang sudah ada sebelum migration ini dan TIDAK diubah:
--
--    migration-45  bundle_flavors(bundle_id, flavor_id)
--                  satu daftar rasa rata untuk SELURUH paket. Ini permintaan
--                  nomor 1: paket lebih murah daripada beli satu-satu.
--    migration-54  bundles.is_fixed
--                  mode "paket terkunci": isi paket = daftar `bundle_flavors`,
--                  pembeli tidak memilih apa-apa. Ini permintaan nomor 2.
--
--  Yang ditambah migration ini adalah mode KETIGA: satu paket, beberapa
--  pilihan, tiap pilihan punya daftar rasa sendiri.
--
-- ---------------------------------------------------------------- MODEL
--
--  Dua tabel baru:
--
--    bundle_slots(bundle_id, slot_index, label_id, label_en)
--    bundle_slot_flavors(bundle_slot_id, flavor_id)
--
--  Satu baris `bundle_slots` = satu "pilihan". `slot_index` mulai dari 1 dan
--  mengikuti urutan yang dilihat pembeli, jadi `slot_index = i` berpasangan
--  dengan `p_bundles[].slots[i-1].flavor_id` di `create_order`. Karena itu
--  bentuk payload order TIDAK berubah sama sekali - hanya isinya yang jadi
--  terikat ke pilihan.
--
--  Tiga keputusan semantik yang sudah dikonfirmasi Steven:
--
--    1. Tiap pilihan mengambil TEPAT SATU rasa. Kalau tiga pilihan, pembeli
--       dapat tiga sando, bukan enam.
--    2. Harga paket di-set admin, satu harga untuk semua kombinasi pilihan.
--       Tidak ada hitungan ulang harga per kombinasi.
--    3. Rasa yang sama BOLEH dipakai di dua pilihan berbeda.
--
-- ---------------------------------------------------------------- MODE
--
--  Tiga mode paket, ditentukan oleh isi tabel - tidak ada kolom boolean baru,
--  supaya tidak ada dua sumber kebenaran yang bisa berbeda:
--
--    (a) ada baris `bundle_slots`      -> MODE PILIHAN   (baru, migration ini)
--    (b) tidak ada slot, `is_fixed`    -> MODE TERKUNCI  (migration-54)
--    (c) tidak ada slot, bukan fixed   -> MODE BIASA     (migration-45)
--
--  `bundles.required_qty` tetap jadi angka yang dibaca `create_order` untuk
--  mengecek jumlah slot dan membagi harga paket. Pada mode (a) nilainya
--  disinkronkan menjadi jumlah baris `bundle_slots` setiap kali paket
--  disimpan, sehingga kedua angka tidak mungkin berbeda.
--
--  Paket yang sudah ada tidak tersentuh: "Sando 2" sekarang tidak punya baris
--  `bundle_slots`, jadi tetap mode (c) dan pembeli bebas memilih 2 rasa
--  seperti biasanya. Mode (a) hanya aktif kalau Steven sengaja membuat
--  baris barunya.
--
-- ---------------------------------------------------------------- ISI FLAT
--
--  `bundle_flavors` (whitelist rata) tidak dihapus saat mode (a) dipakai, dan
--  `create_order` melewatinya kalau grup slot ada. Alasannya: whitelist rata
--  masih berguna untuk paket biasa, dan menghapusnya diam-diam akan membuat
--  admin kembali ke mode (c) lalu menemukan paketnya tiba-tiba terbuka ke
--  semua rasa. Yang berlaku saat mode (a) aktif hanyalah daftar per slot.
--
-- ---------------------------------------------------------------- AKSES
--
--  `bundle_slots` dan `bundle_slot_flavors` mengikuti pola `bundle_flavors`
--  persis: RLS aktif, SELECT publik (dipakai `public_menu()`), dan tulis
--  hanya admin. Penambahan lewat RPC `admin_save_bundle` yang `security
--  definer`, jadi policy tulis hanya lapisan kedua.
--
-- =============================================================================

-- ============================================================ 1. TABEL

create table if not exists public.bundle_slots (
  id         bigint generated by default as identity primary key,
  bundle_id  bigint  not null references public.bundles(id) on delete cascade,
  slot_index integer not null,
  label_id   text    not null default '',
  label_en   text    not null default '',
  constraint bundle_slots_index_positive check (slot_index >= 1),
  constraint bundle_slots_unique_per_bundle unique (bundle_id, slot_index)
);

comment on table public.bundle_slots is
  'Satu baris = satu "pilihan" di dalam paket. Kalau tabel ini punya baris, paket berjalan dalam MODE PILIHAN.';

comment on column public.bundle_slots.slot_index is
  'Urutan pilihan 1..N. Pasangan dengan p_bundles[].slots[slot_index-1] di create_order.';

create table if not exists public.bundle_slot_flavors (
  bundle_slot_id bigint not null references public.bundle_slots(id) on delete cascade,
  flavor_id      bigint not null references public.flavors(id) on delete cascade,
  primary key (bundle_slot_id, flavor_id)
);

comment on table public.bundle_slot_flavors is
  'Rasa yang boleh dipilih untuk satu pilihan. Tiap pilihan mengambil tepat satu rasa dari daftarnya.';

create index if not exists bundle_slot_flavors_flavor_idx
  on public.bundle_slot_flavors (flavor_id);

-- ============================================================ 2. RLS

alter table public.bundle_slots enable row level security;
alter table public.bundle_slot_flavors enable row level security;

drop policy if exists bundle_slots_public_read on public.bundle_slots;
create policy bundle_slots_public_read on public.bundle_slots
  for select to anon, authenticated
  using (true);

drop policy if exists bundle_slots_admin_write on public.bundle_slots;
create policy bundle_slots_admin_write on public.bundle_slots
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists bundle_slot_flavors_public_read on public.bundle_slot_flavors;
create policy bundle_slot_flavors_public_read on public.bundle_slot_flavors
  for select to anon, authenticated
  using (true);

drop policy if exists bundle_slot_flavors_admin_write on public.bundle_slot_flavors;
create policy bundle_slot_flavors_admin_write on public.bundle_slot_flavors
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant select on public.bundle_slots to anon, authenticated;
grant select on public.bundle_slot_flavors to anon, authenticated;
grant all on public.bundle_slots to authenticated;
grant all on public.bundle_slot_flavors to authenticated;

-- ============================================================ 3. BANTUAN
-- Satu helper untuk membaca pilihan sebuah paket sebagai JSON.
-- Dipakai `public_menu()` (pembeli) dan `admin_list_bundles()` (admin),
-- supaya bentuk JSON-nya hanya punya satu definisi di database.
--
-- Hanya membaca `bundle_slots` dan `bundle_slot_flavors`, yang keduanya
-- sudah boleh dibaca publik, jadi tidak menambah permukaan akses baru.

create or replace function public.bundle_slot_groups(p_bundle_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $fn$
  select coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'index', s.slot_index,
        'label_id', s.label_id,
        'label_en', s.label_en,
        'flavor_ids', coalesce((
          select jsonb_agg(bsf.flavor_id order by bsf.flavor_id)
            from public.bundle_slot_flavors bsf
           where bsf.bundle_slot_id = s.id
        ), '[]'::jsonb)
      ) order by s.slot_index
    )
    from public.bundle_slots s
   where s.bundle_id = p_bundle_id
  ), '[]'::jsonb);
$fn$;

grant execute on function public.bundle_slot_groups(bigint)
  to postgres, authenticated, service_role;

