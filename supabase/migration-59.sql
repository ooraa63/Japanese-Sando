         <> v_required_qty then
        raise exception 'flavor_unavailable' using errcode = '22023';
      end if;
      if exists (
        select 1
        from public.bundle_flavors bf
        where bf.bundle_id = v_bundle_id
          and (
            select count(*)
            from jsonb_array_elements(v_slots) s
            where (s ->> 'flavor_id')::bigint = bf.flavor_id
