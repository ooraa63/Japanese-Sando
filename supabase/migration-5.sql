-- =============================================================================
-- 8. Query publik: kategori beserta rasa di dalamnya
-- =============================================================================

create or replace function public.public_menu()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'id', c.id,
      'slug', c.slug,
      'name_id', c.name_id,
      'name_en', c.name_en,
      'desc_id', c.desc_id,
      'desc_en', c.desc_en,
      'image_url', c.image_url,
      'is_featured', c.is_featured,
      'sort_order', c.sort_order,
      'flavors', coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', f.id,
            'slug', f.slug,
            'name_id', f.name_id,
            'name_en', f.name_en,
            'desc_id', f.desc_id,
            'desc_en', f.desc_en,
            'price', f.price,
            'image_url', f.image_url,
            'is_featured', f.is_featured,
            'sort_order', f.sort_order
          ) order by f.sort_order, f.id
        )
        from public.flavors f
        where f.category_id = c.id and f.is_active
      ), '[]'::jsonb)
    ) order by c.sort_order, c.id
  ), '[]'::jsonb)
  from public.categories c
  where c.is_active;
$$;


