create or replace function public.admin_save_category(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id   bigint := nullif(p_payload ->> 'id', '')::bigint;
  v_slug text;
  v_name text;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  v_name := btrim(coalesce(p_payload ->> 'name_id', ''));
  if v_name = '' then
    raise exception 'invalid_name' using errcode = '22023';
  end if;

  v_slug := lower(regexp_replace(
    trim(both '-' from regexp_replace(coalesce(p_payload ->> 'slug', v_name), '[^a-zA-Z0-9]+', '-', 'g')),
    '-', ''
  ));
  if v_slug = '' then
    v_slug := 'kategori-' || substr(md5(random()::text), 1, 6);
  end if;

  -- Hindari bentrok slug
  if v_id is not null then
    if exists (select 1 from public.categories where slug = v_slug and id <> v_id) then
      v_slug := v_slug || '-' || substr(md5(random()::text), 1, 4);
    end if;
  elsif exists (select 1 from public.categories where slug = v_slug) then
    raise exception 'slug_taken' using errcode = '22023';
  end if;

  if v_id is not null then
    update public.categories set
      slug        = v_slug,
      name_id     = v_name,
      name_en     = coalesce(nullif(btrim(coalesce(p_payload ->> 'name_en', '')), ''), v_name),
      desc_id     = coalesce(p_payload ->> 'desc_id', ''),
      desc_en     = coalesce(p_payload ->> 'desc_en', ''),
      image_url   = case when p_payload ? 'image_url'
                         then nullif(trim(coalesce(p_payload ->> 'image_url', '')), '')
                         else image_url end,
      is_active   = coalesce((p_payload ->> 'is_active')::boolean, true),
      is_featured = coalesce((p_payload ->> 'is_featured')::boolean, false),
      sort_order  = coalesce((p_payload ->> 'sort_order')::integer, 0)
    where id = v_id
    returning id into v_id;
  else
    insert into public.categories (
      slug, name_id, name_en, desc_id, desc_en, image_url,
      is_active, is_featured, sort_order
    ) values (
      v_slug, v_name,
      coalesce(nullif(btrim(coalesce(p_payload ->> 'name_en', '')), ''), v_name),
      coalesce(p_payload ->> 'desc_id', ''),
      coalesce(p_payload ->> 'desc_en', ''),
      nullif(trim(coalesce(p_payload ->> 'image_url', '')), ''),
      coalesce((p_payload ->> 'is_active')::boolean, true),
      coalesce((p_payload ->> 'is_featured')::boolean, false),
      coalesce((p_payload ->> 'sort_order')::integer, 0)
    )
    returning id into v_id;
  end if;

  if v_id is null then
    raise exception 'invalid_payload' using errcode = '22023';
  end if;

  return jsonb_build_object('id', v_id, 'slug', v_slug);
end;
$$;

create or replace function public.admin_delete_category(p_category_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_flavors integer;
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  select count(*) into v_flavors
  from public.flavors
  where category_id = p_category_id
    and exists (select 1 from public.orders o
                join public.order_items oi on oi.order_id = o.id
                where oi.flavor_id = flavors.id
                  and o.status in ('pending','accepted','ready'));

  if v_flavors > 0 then
    -- Masih ada rasa yang dipakai pesanan aktif -> nonaktifkan kategorinya
    update public.categories set is_active = false where id = p_category_id;
    return jsonb_build_object('deleted', false, 'deactivated', true);
  end if;

  -- Pindahkan sisa rasa ke kategori pertama yang tersedia
  update public.flavors
  set category_id = (select id from public.categories
                     where id <> p_category_id and is_active
                     order by sort_order, id limit 1)
  where category_id = p_category_id;

  delete from public.categories where id = p_category_id;
  return jsonb_build_object('deleted', true, 'deactivated', false);
end;
$$;

create or replace function public.admin_list_categories()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  return (
    select coalesce(jsonb_agg(
      jsonb_build_object(
        'id', c.id,
        'slug', c.slug,
        'name_id', c.name_id,
        'name_en', c.name_en,
        'desc_id', c.desc_id,
        'desc_en', c.desc_en,
        'image_url', c.image_url,
        'is_active', c.is_active,
        'is_featured', c.is_featured,
        'sort_order', c.sort_order,
        'flavor_count', (select count(*) from public.flavors f
                         where f.category_id = c.id and f.is_active)
      ) order by c.sort_order, c.id
    ), '[]'::jsonb)
    from public.categories c
  );
end;
$$;


