-- 2. HARGA PAKET CUSTOM
--
--    Seller bebas menentukan: beli 2 = 35.000, beli 4 = 65.000, dst.
--    Bentuknya daftar paket di pengaturan:
--      [ { "qty": 2, "price": 35000 }, { "qty": 4, "price": 65000 } ]
--
--    Cara hitung: ambil paket dengan qty TERBESAR yang <= jumlah pesanan.
--    Sisanya dihitung dengan harga satuan biasa.
--
--      1 pcs -> tanpa paket           = 18.000
--      2 pcs -> paket 2              = 35.000
--      3 pcs -> paket 2 + 1 biasa     = 53.000
--      4 pcs -> paket 4              = 65.000
--      5 pcs -> paket 4 + 1 biasa     = 83.000
-- =============================================================================

alter table public.store_settings
  add column if not exists bundle_tiers jsonb not null default '[]'::jsonb;

-- Pindahkan pengaturan lama (paket 2 = 35.000) ke format baru.
update public.store_settings set
  bundle_tiers = '[{"qty": 2, "price": 35000}]'::jsonb
where id = 1
  and (bundle_tiers is null or jsonb_array_length(bundle_tiers) = 0)
  and bundle_enabled;


-- Fungsi bantu: pilih paket-paket yang dipakai untuk sejumlah pcs.
--
-- Paket ditumpuk: pakai paket dengan qty terbesar yang masih muat, sebanyak
-- mungkin, lalu sisanya dibayar harga satuan. Jadi dengan paket
-- (2 = 35.000) dan (4 = 65.000):
--   1 pcs -> 18.000
--   3 pcs -> paket 2 + 1 biasa          = 53.000
--   6 pcs -> paket 4 + paket 2           = 100.000
--   7 pcs -> paket 4 + paket 2 + 1 biasa = 118.000
create or replace function public.pick_bundles(
  p_tiers jsonb,
  p_total integer
) returns jsonb
language plpgsql
immutable
as $$
declare
  v_tier   jsonb;
  v_left   integer := coalesce(p_total, 0);
  v_result jsonb := '[]'::jsonb;
begin
  if p_total is null or p_total < 2
     or jsonb_array_length(coalesce(p_tiers, '[]'::jsonb)) = 0 then
    return v_result;
  end if;

  while v_left >= 2 loop
    -- paket dengan qty terbesar yang masih muat
    v_tier := null;
    select t into v_tier
    from jsonb_array_elements(p_tiers) as t
    where (t ->> 'qty') ~ '^[0-9]+$'
      and (t ->> 'price') ~ '^[0-9]+$'
      and (t ->> 'qty')::int >= 2
      and (t ->> 'qty')::int <= v_left
    order by (t ->> 'qty')::int desc
    limit 1;

    exit when v_tier is null;

    v_result := v_result || jsonb_build_array(v_tier);
    v_left := v_left - (v_tier ->> 'qty')::int;
  end loop;

  return v_result;
end;
$$;


